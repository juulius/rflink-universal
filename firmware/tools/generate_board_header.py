#!/usr/bin/env python3
"""RFLink board profile -> C++ constants; zero external Python dependencies.

Run before build. CMake also regenerates the header at configure time.
Do not use for a live web pin remapping or to alter an active SPI bus.
"""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_PROFILE = ROOT / 'boards' / 'rflink_s3_n16r8.json'
DEFAULT_HEADER = ROOT / 'components' / 'rflink_radio_hal' / 'include' / 'rflink_board_generated.hpp'
# Deliberate conservative ESP32-S3 N16R8 whitelist. USB (19/20), UART
# console (43/44), strapping (0/3/45/46) and flash/PSRAM signals are excluded.
GPIO_ALLOWED = set([1,2,*range(4,19),21,*range(38,43),47,48])
EXPECTED = [('43342',433420000,'ook'),('43392',433920000,'ook'),('86830',868300000,'fsk2')]

class ProfileError(ValueError): pass

def load(path=DEFAULT_PROFILE):
    obj=json.loads(Path(path).read_text(encoding='utf-8'))
    if obj.get('schema') != 1: raise ProfileError('Unsupported board schema')
    bid=obj.get('board_id')
    if not isinstance(bid,str) or not re.fullmatch(r'[a-z0-9-]{3,36}',bid):
        raise ProfileError('board_id must be 3..36 lowercase letters/numbers/dashes')
    if obj.get('mcu') != 'ESP32-S3-WROOM-1-N16R8':
        raise ProfileError('Wrong MCU for this N16R8 build')
    spi=obj.get('spi')
    if not isinstance(spi,dict): raise ProfileError('spi is missing')
    speed=spi.get('clock_hz')
    if type(speed) is not int or not 100_000 <= speed <= 6_000_000:
        raise ProfileError('SPI clock_hz must be 100000..6000000; do not exceed 6 MHz on this PCB before measurement')
    radios=obj.get('radios')
    if not isinstance(radios,list) or len(radios)!=3:
        raise ProfileError('Exactly three radios required in fixed order: 43342, 43392, 86830')
    used={}
    def add_pin(label,pin):
        if type(pin) is not int or pin not in GPIO_ALLOWED:
            raise ProfileError(f'{label}: GPIO {pin!r} not allowed on this N16R8 hardware profile')
        if pin in used: raise ProfileError(f'GPIO {pin} used twice: {used[pin]} and {label}')
        used[pin]=label
    for name in ('sclk','mosi','miso'):add_pin('spi.'+name,spi.get(name))
    for i,(r,ex) in enumerate(zip(radios,EXPECTED)):
        if not isinstance(r,dict) or (r.get('id'),r.get('frequency_hz'),r.get('modulation'))!=ex:
            raise ProfileError(f'radios[{i}] identity/frequency/modulation mismatch; RF profile is separate')
        for name in ('cs','gdo0','gdo2'):add_pin(f'radios[{i}].{name}',r.get(name))
    return obj

def board_hash(obj):
    # Only identity & actual hardware matter. Comments/help keys excluded.
    hardware={'schema':obj['schema'],'board_id':obj['board_id'],'mcu':obj['mcu'],
              'spi':{k:obj['spi'][k] for k in ('sclk','mosi','miso','clock_hz')},
              'radios':[{k:r[k] for k in ('id','frequency_hz','modulation','cs','gdo0','gdo2')} for r in obj['radios']]}
    raw=json.dumps(hardware,sort_keys=True,separators=(',',':')).encode()
    return hashlib.sha256(raw).hexdigest()[:8]

def render(obj):
    spi=obj['spi']; radios=obj['radios']; digest=board_hash(obj)
    rows=',\n'.join('  {{{cs},{gdo0},{gdo2},{frequency_hz},Modulation::{modulation}}}'.format(**r) for r in radios)
    return ('#pragma once\n// GENERATED by tools/generate_board_header.py. Edit boards/rflink_s3_n16r8.json, NOT this header.\n'
            '// Included from rflink_radio_hal.hpp, inside namespace rflink.\n'
            f'inline constexpr char kBoardId[] = "{obj["board_id"]}";\n'
            f'inline constexpr char kBoardHash[] = "{digest}";\n'
            f'inline constexpr SpiPins kSpiPins{{{spi["sclk"]},{spi["mosi"]},{spi["miso"]},{spi["clock_hz"]}}};\n'
            'inline constexpr std::array<RadioPins,3> kRadioPins{{\n'+rows+'\n}};\n').replace('\\n','\n')

def main():
    p=argparse.ArgumentParser()
    p.add_argument('--input',type=Path,default=DEFAULT_PROFILE)
    p.add_argument('--output',type=Path,default=DEFAULT_HEADER)
    p.add_argument('--print-hash',action='store_true')
    p.add_argument('--check',action='store_true')
    a=p.parse_args()
    try:
        obj=load(a.input); content=render(obj)
        if a.check:
            if not a.output.exists() or a.output.read_text(encoding='utf-8')!=content:
                raise ProfileError('Generated header is stale. Run tools/generate_board_header.py')
        elif not a.output.exists() or a.output.read_text(encoding='utf-8')!=content:
            a.output.parent.mkdir(parents=True,exist_ok=True)
            a.output.write_text(content,encoding='utf-8')
        if a.print_hash: print(board_hash(obj))
        else: print(f'PASS board {obj["board_id"]}, hash={board_hash(obj)}, SPI={obj["spi"]["clock_hz"]} Hz; unique safe GPIOs')
    except (ProfileError,ValueError,OSError,KeyError,TypeError) as exc:
        print(f'FAIL board profile: {exc}',file=sys.stderr)
        return 1
    return 0
if __name__=='__main__':sys.exit(main())
