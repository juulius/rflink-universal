void DeveloperSession::reset() {
  baseline_mode_ = false;
  capturing_ = false;
  label_.clear();
  baseline_hashes_.clear();
  candidates_.clear();
  captures_.clear();
}

void DeveloperSession::start_baseline(uint8_t channel) {
  reset();
  channel_ = channel;
  baseline_mode_ = true;
  label_ = "baseline";
}

void DeveloperSession::finish_baseline() {
  baseline_mode_ = false;
  capturing_ = false;
  candidates_.clear();
}

void DeveloperSession::start_action(uint8_t channel, const std::string &label) {
  channel_ = channel;
  baseline_mode_ = false;
  capturing_ = true;
  label_ = label;
  candidates_.clear();
}

bool DeveloperSession::baseline_contains_(uint32_t hash) const {
  return std::find(baseline_hashes_.begin(), baseline_hashes_.end(), hash) != baseline_hashes_.end();
}

void DeveloperSession::observe(uint32_t hash, const RFFrame &frame, uint16_t pulse_count) {
  if (frame.channel != channel_) return;
  if (baseline_mode_) {
    if (!baseline_contains_(hash)) baseline_hashes_.push_back(hash);
    return;
  }
  // Keep a few complete, labelled examples for offline replay. Never retain
  // unbounded radio traffic or samples from the background calibration.
  if (capturing_ && !baseline_contains_(hash) && user_vm::identifier(label_) && captures_.size() < 12 &&
      ((frame.kind == FrameKind::RAW && frame.raw != nullptr && frame.raw->size() <= 512) ||
       (frame.kind == FrameKind::PACKET && frame.packet != nullptr && frame.packet->size() <= 64))) {
    const auto count = std::count_if(captures_.begin(), captures_.end(), [&](const CapturedFrame &c) {
      return c.label == label_ && c.hash == hash;
    });
    if (count < 3) {
      CapturedFrame sample;
      sample.channel = frame.channel;
      sample.kind = frame.kind;
      sample.label = label_;
      sample.hash = hash;
      if (frame.raw) sample.raw = *frame.raw;
      if (frame.packet) sample.packet = *frame.packet;
      captures_.push_back(std::move(sample));
    }
  }
  auto it = std::find_if(candidates_.begin(), candidates_.end(), [&](const DeveloperCandidate &c) { return c.hash == hash; });
  if (it == candidates_.end()) {
    DeveloperCandidate c;
    c.hash = hash;
    c.first_seen_ms = frame.received_ms;
    c.last_seen_ms = frame.received_ms;
    c.pulse_count = pulse_count;
    c.frame_kind = frame.kind;
    c.was_in_baseline = baseline_contains_(hash);
    candidates_.push_back(c);
    it = candidates_.end() - 1;
  }
  it->observations++;
  it->last_seen_ms = frame.received_ms;
  if (frame.has_rssi) {
    it->has_rssi = true;
    it->best_rssi_dbm = std::max(it->best_rssi_dbm, frame.rssi_dbm);
  }
}

void DeveloperSession::annotate(uint32_t hash, const DecodeResult &result, uint8_t decoder_confidence) {
  auto it = std::find_if(candidates_.begin(), candidates_.end(), [&](const DeveloperCandidate &c) { return c.hash == hash; });
  if (it == candidates_.end()) return;
  it->protocol = result.protocol;
  it->identity_key = result.identity_key;
  it->action = result.action;
  it->decoder_confidence = decoder_confidence;
}

const DeveloperCandidate *DeveloperSession::best_new_candidate() const {
  const DeveloperCandidate *best = nullptr;
  for (const auto &candidate : candidates_) {
    if (candidate.was_in_baseline) continue;
    if (best == nullptr || candidate.observations > best->observations ||
        (candidate.observations == best->observations && candidate.has_rssi &&
         (!best->has_rssi || candidate.best_rssi_dbm > best->best_rssi_dbm))) {
      best = &candidate;
    }
  }
  return best;
}

std::string DeveloperSession::generate_raw_decoder_snippet(const DeveloperCandidate &candidate) const {
  std::ostringstream out;
  out << "// Generated by RFLink Developer Mode. Verify timings/identity before committing.\n"
      << "if (frame.kind != FrameKind::RAW || frame.channel != " << static_cast<unsigned>(channel_) << ") return 0;\n"
      << "if (frame.raw == nullptr || frame.raw->size() != " << candidate.pulse_count << ") return 0;\n"
      << "// TODO: add sync/header/timing checks so this decoder cannot steal other protocols.\n"
      << "return 70;\n";
  return out.str();
}

std::string DeveloperSession::generate_packet_decoder_snippet(const std::vector<uint8_t> &packet) const {
  std::ostringstream out;
  out << "// Packet fingerprint. Replace volatile counter/checksum bytes with masks.\n"
      << "static const uint8_t sample[] = {";
  for (size_t i = 0; i < packet.size(); i++) {
    char b[8];
    std::snprintf(b, sizeof(b), "0x%02X", packet[i]);
    if (i) out << ", ";
    out << b;
  }
  out << "};\n";
  return out.str();
}

std::string DeveloperSession::generate_packet_decoder_snippet(const DeveloperCandidate &candidate) const {
  std::ostringstream out;
  out << "// Generated by RFLink Developer Mode. Verify identity/counter/checksum fields.\n"
      << "if (frame.kind != FrameKind::PACKET || frame.channel != " << static_cast<unsigned>(channel_) << ") return 0;\n"
      << "if (frame.packet == nullptr || frame.packet->size() != " << candidate.pulse_count << ") return 0;\n"
      << "// TODO: compare stable header bytes and mask counters/checksums.\n"
      << "return 70;\n";
  return out.str();
}

