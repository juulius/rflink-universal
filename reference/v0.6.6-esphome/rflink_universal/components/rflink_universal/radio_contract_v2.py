"""Radio Engine v2: one manifest contract for every built-in protocol.

The contract describes requested input, permitted physical bands and reviewed TX
capabilities. It does not configure GPIO/SPI/CC1101, nor authorize transmitting.
"""
import json

BANDS = {"433.42": 0, "433.92": 1, "868.30": 2, "example": 255}
KINDS = {"raw": 1, "packet": 2}
RX_METHODS = {"raw_rmt", "spi_packet", "spi_fifo_sync", "spi_fifo_raw", "uart_stream"}
TX_METHODS = {"legacy_tx_engine", "disabled"}
TX_TRANSPORTS = {"none": "NONE", "rmt_raw": "RMT_RAW", "spi_fifo_packet": "SPI_FIFO_PACKET", "gdo_serial": "GDO_SERIAL"}



def validate_contract(manifest):
    for cap in manifest["capabilities"]:
        protocol = cap["protocol"]
        contract = cap.get("radio_v2")
        if not isinstance(contract, dict) or set(contract) != {"rx", "tx"}:
            raise ValueError(f"{protocol}: radio_v2 must contain rx and tx")
        rx, tx = contract["rx"], contract["tx"]
        if not isinstance(rx, dict) or set(rx) != {"routes"} or not isinstance(rx["routes"], list) or not rx["routes"]:
            raise ValueError(f"{protocol}: at least one RX route required")
        seen = set()
        for route in rx["routes"]:
            if not isinstance(route, dict) or set(route) != {"band", "kind", "method", "profile"}:
                raise ValueError(f"{protocol}: invalid RX route fields")
            band, kind, method, profile = (route[k] for k in ("band", "kind", "method", "profile"))
            if band not in BANDS or band not in manifest["bands"] or kind not in KINDS or kind not in manifest["modes"] or method not in RX_METHODS:
                raise ValueError(f"{protocol}: unsupported radio band/kind/method")
            if kind == "raw" and method != "raw_rmt" or kind == "packet" and method == "raw_rmt":
                raise ValueError(f"{protocol}: incompatible method for frame format")
            if not isinstance(profile, str) or not profile or len(profile) > 64:
                raise ValueError(f"{protocol}: invalid profile name")
            if (band, kind, method) in seen:
                raise ValueError(f"{protocol}: duplicate RX route")
            seen.add((band, kind, method))
        if not isinstance(tx, dict) or set(tx) != {"method", "status", "band", "transport"}:
            raise ValueError(f"{protocol}: invalid TX contract")
        transport = tx["transport"]
        if not isinstance(transport, dict) or set(transport) != {"preferred", "fallback", "profile"}:
            raise ValueError(f"{protocol}: TX transport requires preferred, fallback and profile")
        primary, backup, profile = transport["preferred"], transport["fallback"], transport["profile"]
        if primary not in TX_TRANSPORTS or backup not in TX_TRANSPORTS or primary == "none" and backup != "none":
            raise ValueError(f"{protocol}: invalid TX transport")
        if not isinstance(profile, str) or not profile or len(profile) > 64:
            raise ValueError(f"{protocol}: invalid TX physical preset")
        if cap["transmit"]["status"] == "disabled" and cap["transmit"]["encoder"] == "none" and backup != "none":
            raise ValueError(f"{protocol}: disabled TX cannot have a fallback")
        # Existing reviewed encoders are pulse or packet encoders respectively;
        # a new physical route requires an explicit compatible encoder first.
        encoder_id = cap["transmit"]["encoder"]
        if encoder_id != "none":
            expected = "spi_fifo_packet" if encoder_id == "itho_rft" else "gdo_serial" if encoder_id == "ramses_ii" else "rmt_raw"
            if primary != expected or backup != "none":
                raise ValueError(f"{protocol}: route must match reviewed TX encoder")
        declared = cap["transmit"]
        expected_status = declared["status"]
        expected_band = declared.get("radio", "") if declared["encoder"] != "none" else ""
        expected_method = "disabled" if declared["encoder"] == "none" else "legacy_tx_engine"
        if {k: tx[k] for k in ("method", "status", "band")} != {"method": expected_method, "status": expected_status, "band": expected_band}:
            raise ValueError(f"{protocol}: TX contract must mirror reviewed encoder; cannot grant TX")
        if declared["encoder"] != "none" and primary == "none":
            raise ValueError(f"{protocol}: reviewed TX encoder missing physical route")
    return True


def generate_contract_header(packs):
    lines = ["// AUTOGENERATED FROM radio_v2 decoder manifests; DO NOT EDIT.\n", "#pragma once\n",
             '#if __has_include("radio_contract_v2.h")\n'
             '# include "radio_contract_v2.h"\n'
             '#elif __has_include("../esphome/components/rflink_universal/radio_contract_v2.h")\n'
             '# include "../esphome/components/rflink_universal/radio_contract_v2.h"\n'
             '#else\n'
             '# error "RFLink: radio_contract_v2.h missing"\n'
             '#endif\n',
             "namespace esphome { namespace rflink_universal { namespace radio_v2_catalog {\n",
             "inline const RadioInputSpec *specs(size_t &n) { static const RadioInputSpec table[] = {\n"]
    for _, manifest in packs:
        validate_contract(manifest)
        for cap in manifest["capabilities"]:
            for route in cap["radio_v2"]["rx"]["routes"]:
                method = route["method"]
                lines.append('  {' + ', '.join([
                    json.dumps(cap["protocol"]), str(BANDS[route["band"]]),
                    'InputKind::RAW' if route["kind"] == "raw" else 'InputKind::PACKET',
                    json.dumps(route["profile"]), json.dumps(method)]) + '},\n')
    lines += ["}; n=sizeof(table)/sizeof(table[0]); return table; }\n",
              "inline const RadioInputIndex &index() { static const RadioInputIndex i(specs_counted(), size()); return i; }\n",
              "inline size_t size() { size_t n; specs(n); return n; }\n",
              "inline const RadioInputSpec *specs_counted() { size_t n; return specs(n); }\n",
              "}}}\n"]
    # Because C++ requires declarations before use, put helpers in declaration order.
    # Replace helper region with a simple function-local cached pair.
    start = next(i for i,s in enumerate(lines) if s.startswith('inline const RadioInputIndex &index'))
    lines[start:] = [
        "inline const RadioInputIndex &index() { size_t n=0; const auto *p=specs(n); static const RadioInputIndex idx(p,n); return idx; }\n",
        "inline const RadioTxSpec *tx_specs(size_t &n) { static const RadioTxSpec table[] = {\n",
    ]
    for _, manifest in packs:
        for cap in manifest["capabilities"]:
            tx = cap["radio_v2"]["tx"]
            t = tx["transport"]
            band = tx["band"] or (manifest["bands"][0] if len(manifest["bands"]) == 1 else "example")
            lines.append("  {" + ", ".join([json.dumps(cap["protocol"]), str(BANDS[band]),
                "TxTransport::" + TX_TRANSPORTS[t["preferred"]],
                "TxTransport::" + TX_TRANSPORTS[t["fallback"]],
                json.dumps(t["profile"]),
                "true" if cap["transmit"]["encoder"] != "none" and cap["transmit"]["status"] != "disabled" else "false",
            ]) + "},\n")
    lines.extend([
        "}; n=sizeof(table)/sizeof(table[0]); return table; }\n",
        "inline const RadioTxSpec *tx_for(const char *protocol) { size_t n=0; const auto *p=tx_specs(n); for(size_t i=0;i<n;++i) if(protocol && std::strcmp(p[i].protocol,protocol)==0) return &p[i]; return nullptr; }\n",
        "}}}\n",
    ])
    return "".join(lines)
