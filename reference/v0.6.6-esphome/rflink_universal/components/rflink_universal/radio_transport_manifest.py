"""Schema-2 decoder transport metadata -> immutable C++ radio contracts.

Only explicitly declared, reviewed transports are exposed. No runtime firmware
scripts can remap a GPIO or override a physical radio's safety policy.
"""
import json

TRANSPORTS = {"spi_packet": "SPI_PACKET", "spi_fifo_sync": "SPI_FIFO_SYNC",
              "spi_fifo_raw": "SPI_FIFO_RAW", "uart_stream": "UART_STREAM"}
RADIO_INDEX = {"433.42": 0, "433.92": 1, "868.30": 2}


def validate_radio_transport(manifest):
    radio = manifest.get("radio_transport")
    if radio is None:
        return  # Old decoder packs have no transport ownership requirements.
    if not isinstance(radio, dict) or not {"radio", "preferred_rx", "fallback_rx", "max_window_ms"}.issubset(radio) or set(radio)-{"radio", "preferred_rx", "fallback_rx", "max_window_ms", "scan_every_ms", "scan_window_ms"}:
        raise ValueError("radio_transport requires radio, preferred_rx, fallback_rx, max_window_ms (optional scan timing)")
    if radio["radio"] not in RADIO_INDEX or radio["radio"] not in manifest["bands"]:
        raise ValueError("radio_transport radio must be one of the decoder's declared bands")
    if radio["preferred_rx"] not in TRANSPORTS:
        raise ValueError("unknown preferred radio transport")
    if radio["fallback_rx"] != "none" and radio["fallback_rx"] not in TRANSPORTS:
        raise ValueError("unknown fallback radio transport")
    if radio["fallback_rx"] == radio["preferred_rx"]:
        raise ValueError("fallback and preferred transport cannot be the same")
    if type(radio["max_window_ms"]) is not int or not 20 <= radio["max_window_ms"] <= 30000:
        raise ValueError("invalid maximum radio lease duration")
    if radio["preferred_rx"] == "uart_stream" and radio["radio"] != "868.30":
        raise ValueError("UART stream is currently supported only for the 868 MHz radio")
    interval=radio.get("scan_every_ms",0)
    window=radio.get("scan_window_ms",0)
    if (type(interval) is not int or type(window) is not int or
        (interval==0 and window!=0) or
        (interval!=0 and not (1000<=interval<=60000 and 20<=window<=min(1000,interval//5,radio["max_window_ms"])))):
        raise ValueError("automatic RX scan must be off or use a bounded <=20% radio duty share")
    if interval and radio["preferred_rx"] == "spi_packet":
        raise ValueError("primary packet receivers are always-on, not time-sliced")
    return radio


def generate_radio_header(packs):
    rows = []
    for _, manifest in packs:
        radio = validate_radio_transport(manifest)
        if not radio:
            continue
        for cap in manifest["capabilities"]:
            primary = TRANSPORTS[radio["preferred_rx"]]
            fallback = TRANSPORTS.get(radio["fallback_rx"], "NONE")
            rows.append((cap["protocol"], RADIO_INDEX[radio["radio"]], primary,
                         fallback, radio["max_window_ms"], radio.get("scan_every_ms",0),radio.get("scan_window_ms",0)))
    out = ["// AUTOGENERATED: decoder-manifest radio contracts; DO NOT EDIT.\n",
           "#pragma once\n"
           "// ESPHome generated catalog is in src/rflink_decoders; host catalog is in the component.\n"
           "#if __has_include(\"radio_transport_policy.h\")\n"
           "# include \"radio_transport_policy.h\"\n"
           "#elif __has_include(\"../esphome/components/rflink_universal/radio_transport_policy.h\")\n"
           "# include \"../esphome/components/rflink_universal/radio_transport_policy.h\"\n"
           "#else\n"
           "# error \"RFLink: radio_transport_policy.h missing\"\n"
           "#endif\n",
           "namespace esphome { namespace rflink_universal { namespace radio_catalog {\n",
           "inline RadioTransportPolicy policy() {\n",
           "  static const DecoderRadioSpec specs[] = {\n"]
    for protocol, index, preferred, fallback, window, period, scan in rows:
        out.append(f"    {{{json.dumps(protocol)}, {index}, RxTransport::{preferred}, RxTransport::{fallback}, {window}, {period}, {scan}}},\n")
    if not rows:
        out.append("    {nullptr, 0, RxTransport::NONE, RxTransport::NONE, 20, 0, 0},\n")
    out.append("  };\n")
    out.append(f"  return RadioTransportPolicy(specs,{len(rows)});\n")
    out.append("}\n}}}\n")
    return "".join(out)
